#include "cobra.h"
#include "math_3d.h"   // project(), rotateFast()

// Scale — підніми до ~1.4–1.6, якщо корабль здасться занадто малим/плоским.
#define COBRA_SCALE 1.5f

// 28 вершин: 12 основного корпусу + 8 основних двигунів (лівий/правий) + 6
// деталей малих бічних двигунів ззаду + 2 лазера (кінчик носа → дуло). Джерело —
// канонічні дані Ian Bell/David Braben з оригінальної Elite (1984), секція
// "COBRA" (= Cobra Mk III; є ще окремий "COBRAMK1" — інший, менший корабель,
// не плутати). Це ВСІ 28 оригінальних вершин — лазер у первинних даних був
// позначений як "fails" (2-вершинна "грань", яку тодішній рендерер не тягнув
// як трикутник), але як звичайне РЕБРО (лінія) він малюється без проблем.
//
// Координати зсунуті так, щоб bounding-box-центр моделі був у (0,0,0):
// оригінальні дані мали центр приблизно (0, 1, 18) (порахований по 12
// вершинах корпусу — додані двигуни/лазер лежать у тих самих межах
// або виступають лише трохи вперед, тож центр навмисно НЕ перераховувався
// під них — лазер має лишитись тонким виступом з носа, а не сколихнути
// центр обертання всього корабля), а обертання (rotateFast) завжди
// відбувається навколо локального початку координат — тому без зсуву
// корабель оберталний не навколо власного центру, а навколо точки
// віддаленої на 18 одиниць по Z.
//
// x та y тут ще й інвертовані (x,y → -x,-y, z без змін) відносно
// геометрії — це власне обертання моделі на 180° навколо її Z-осі
// (визначник +1, порядок вершин граней лишається коректним), яке ставить
// купол кабіни (раніше внизу) нагору. Ніс/корма (вісь Z) не займані.
// Оскільки корабель ліво-право симетричний, інверсія X непомітна.
static const int COBRA_VERTICES = 28;

static const Point3D cobra_vertices[COBRA_VERTICES] = {
    { -32,   1,  58}, // 0  ніс, лівий верх
    {  32,   1,  58}, // 1  ніс, правий верх
    {   0, -25,   6}, // 2  купол кабіни
    { 120,   4, -26}, // 3  праве тіло, середа
    { -120,  4, -26},  // 4  ліве тіло, середа
    {  88, -15, -58},  // 5  прав задній верх
    { -88, -15, -58},  // 6  лів задній верх
    { -128,  9, -58},  // 7  лів кінець крила
    {  128,  9, -58},  // 8  прав кінець крила
    {   0, -25, -58},  // 9  задній центр, верх
    {  32,  25, -58},  // 10 прав задній живіт
    { -32,  25, -58},  // 11 лів задній живіт
    // Ці 8 вершин НЕ групуються по сусідніх номерах — основні двигуни визначаються
    // знаком X (canonical-парність збережена з оригінальних даних):
    // правий основний двигун = {12,13,18,19}, лівий = {14,15,16,17}.
    {  36,  -7, -58},  // 12 правий двигун
    {   8, -11, -58},  // 13 правий двигун
    {  -8, -11, -58},  // 14 лівий двигун
    { -36,  -7, -58},  // 15 лівий двигун
    { -36,  13, -58},  // 16 лівий двигун
    {  -8,  17, -58},  // 17 лівий двигун
    {   8,  17, -58},  // 18 правий двигун
    {  36,  13, -58},  // 19 правий двигун
    // Деталі мотогондоли, правий борт (трикутник 20-21-22)
    {  80,   7, -58},  // 20
    {  80,  -5, -58},  // 21
    {  88,   1, -58},  // 22
    // Деталі мотогондоли, лівий борт (трикутник 23-24-25)
    { -80,  -5, -58},  // 23
    { -88,   1, -58},  // 24
    { -80,   7, -58},  // 25
    // Лазер: від носа (той самий z, що й вершини 0/1) вперед до дула
    {   0,   1,  58},  // 26 основа лазера, центр носа
    {   0,   1,  72},  // 27 дуло лазера
};

// 39 унікальних ребер: 24 базового корпусу + 14 деталей двигунів +
// 1 лазер (по 4 на кожен основний двигун — межі чотирикутника, без внутрішньої
// діагоналі тріангуляції — і по 3 на кожен трикутник мотогондоли).
static const int cobra_edges[39][2] = {
    // Носова частина (конус + живіт)
    {0,1}, {1,2}, {0,2},
    {1,10}, {10,11}, {0,11},
    // Верхні ребра тіла
    {2,6}, {0,6}, {0,4}, {4,6},
    // Ребра до кінців крил
    {4,7}, {7,11}, {2,5}, {1,5},
    // Ліве/ праве крило + задня частина
    {1,3}, {3,5}, {3,8}, {8,10},
    // Задній шестигранник (двунь)
    {5,9}, {2,9}, {6,9}, {5,8}, {6,7}, {5,6},
    // Правий основний двигун (12,13,18,19)
    {19,12}, {12,13}, {13,18}, {18,19},
    // Лівий основний двигун (14,15,16,17)
    {17,14}, {14,15}, {15,16}, {16,17},
    // Деталь мотогондоли, правий борт
    {20,21}, {21,22}, {22,20},
    // Деталь мотогондоли, лівий борт
    {23,24}, {24,25}, {25,23},
    // Лазер
    {26,27},
};

// 26 трикутників-граней: 20 основного корпусу (триангуляція IndexedFaceSet
// з cobra3.wrl) + 6 нових деталей (2 основні двигуни × 2 трикутники + 2 малі бічні).
// Порядок вершин нормалізовано так, щоб усі нормалі дивились НАЗОВНІ
// (проти годинникової стрілки, якщо дивитись ззовні) — це дає коректний
// backface-culling через знак площі проекції на екран (див. drawCobra).
static const int cobra_faces[26][3] = {
    {0,2,1},
    {0,1,10},{0,10,11},
    {0,6,2},
    {0,4,6},
    {0,7,4},{0,11,7},
    {1,2,5},
    {1,5,3},
    {1,3,8},{1,8,10},
    {2,9,5},
    {2,6,9},
    {3,5,8},
    {4,7,6},
    // задній «двунь»: семикутник 5,8,10,11,7,6,9 (віяло від вершини 5)
    {5,10,8},{5,11,10},{5,7,11},{5,6,7},{5,9,6},
    // правий основний двигун (12,13,18,19; діагональ 19-13)
    {19,12,13},{19,13,18},
    // лівий основний двигун (14,15,16,17; діагональ 17-15)
    {17,14,15},{17,15,16},
    // деталі мотогондол
    {21,20,22},
    {25,23,24},
};

// Для кожного з 39 ребер — індекси граней (з cobra_faces), яким воно
// належить. Базові 24 ребра корпусу — по 2 грані (модель замкнена: кожне
// таке ребро спільне рівно для 2 граней). Нові 14 ребер деталей плюс лазер —
// це межі окремо "накладених" елементів (не частина замкненого корпусу),
// тож у них лише ОДНА власна грань — вона продубльована двічі, щоб той
// самий алгоритм видимості ("ребро видиме, якщо хоч одна з двох граней
// дивиться на камеру") працював без змін. Лазер прив'язаний до головної
// носової грані (0) — коли ніс відвернутий від камери, лазер теж ховається.
static const int cobra_edge_faces[39][2] = {
    {0,1},{0,7},{0,3},
    {1,10},{2,16},{2,6},
    {3,12},{3,4},{4,5},{4,14},
    {5,14},{6,17},{7,11},{7,8},
    {8,9},{8,13},{9,13},{10,15},
    {11,19},{11,12},{12,19},{13,15},{14,18},{18,19},
    // правий основний двигун: {19,12,13},{19,13,18} = грані 20,21
    {20,20},{20,20},{21,21},{21,21},
    // лівий основний двигун: {17,14,15},{17,15,16} = грані 22,23
    {22,22},{22,22},{23,23},{23,23},
    // мотогондола, правий борт = грань 24
    {24,24},{24,24},{24,24},
    // мотогондола, лівий борт = грань 25
    {25,25},{25,25},{25,25},
    // лазер = головна носова грань 0
    {0,0},
};

static void drawLineSafe(TFT_eSprite &canvas, Point2D p1, Point2D p2,
                         uint16_t color) {
    if (p1.valid && p2.valid) {
        canvas.drawLine(p1.x, p1.y, p2.x, p2.y, color);
    }
}

void drawCobra(TFT_eSprite &canvas, float ax, float ay, float az,
               float gx, float gy, float gz, uint16_t color, bool wireframe,
               int *faces_visible) {
    Point2D pts[COBRA_VERTICES];
    Point3D rot[COBRA_VERTICES];

    for (int i = 0; i < COBRA_VERTICES; i++) {
        Point3D v = cobra_vertices[i];
        v.x *= COBRA_SCALE;
        v.y *= COBRA_SCALE;
        v.z *= COBRA_SCALE;
        rot[i] = rotateFast(v);          // обертання у мировому просторі
        pts[i] = project(rot[i], gx, gy, gz);
    }

    // Backface culling: знак площі проекції трикутника на екран однозначно
    // визначає, чи грань дивиться на камеру (при послідовному порядку
    // вершин усіх граней). Ніякого z-буфера чи дискретизації — просто
    // і, для цієї моделі, завжди точно (перевірено окремо проти повного
    // побіксельного z-тесту — результати збігаються в усіх орієнтаціях).
    static char face_front[26];
    int count = 0;
    for (int f = 0; f < 26; f++) {
        Point2D &pa = pts[cobra_faces[f][0]];
        Point2D &pb = pts[cobra_faces[f][1]];
        Point2D &pc = pts[cobra_faces[f][2]];
        if (!pa.valid || !pb.valid || !pc.valid) {
            face_front[f] = 0;
            continue;
        }
        float area = (float)(pb.x - pa.x) * (pc.y - pa.y) -
                     (float)(pb.y - pa.y) * (pc.x - pa.x);
        face_front[f] = (area < 0.0f) ? 1 : 0;
        if (face_front[f]) count++;
    }
    if (faces_visible) *faces_visible = count;

    if (!wireframe) {
        // Painter's algorithm: малюємо видимі грані від найдальшої до
        // найближчої, щоб перекриття (наприклад, у задньому шестикутнику)
        // виглядало коректно.
        static int visible[26];
        int vc = 0;
        for (int f = 0; f < 26; f++) if (face_front[f]) visible[vc++] = f;

        static float fz[26];
        for (int i = 0; i < vc; i++) {
            int f = visible[i];
            Point2D &pa = pts[cobra_faces[f][0]];
            Point2D &pb = pts[cobra_faces[f][1]];
            Point2D &pc = pts[cobra_faces[f][2]];
            fz[i] = (pa.z + pb.z + pc.z) / 3.0f;
        }
        for (int i = 0; i < vc; i++) {
            for (int j = i + 1; j < vc; j++) {
                if (fz[j] > fz[i]) {
                    float tz = fz[i]; fz[i] = fz[j]; fz[j] = tz;
                    int tv = visible[i]; visible[i] = visible[j]; visible[j] = tv;
                }
            }
        }

        for (int i = 0; i < vc; i++) {
            int f = visible[i];
            Point2D &a = pts[cobra_faces[f][0]];
            Point2D &b = pts[cobra_faces[f][1]];
            Point2D &c = pts[cobra_faces[f][2]];

            // Solid: чорне непрозоре заповнення (CL_BG). Так тіло перекриває
            // частинки/фон позаду — як автентичний Elite (через передню
            // стінку не видно дальних ребер). Затінення тут не треба: тіло
            // і так чорне, а яскравість дають ребра.
            canvas.fillTriangle(a.x, a.y, b.x, b.y, c.x, c.y, CL_BG);
        }
    }

    // Ребра: у wireframe малюємо всі (каркас без приховування), у solid —
    // лише ті, що належать хоч одній грані "обличчям до камери" (інакше
    // "задні" ребра просвічували б крізь суцільний корпус).
    for (int e = 0; e < 39; e++) {
        if (wireframe ||
            face_front[cobra_edge_faces[e][0]] ||
            face_front[cobra_edge_faces[e][1]]) {
            drawLineSafe(canvas, pts[cobra_edges[e][0]],
                               pts[cobra_edges[e][1]], color);
        }
    }
}
